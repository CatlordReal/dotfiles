  flavour="$(normalise_flavour "$1")"
  theme="$(kitty_theme_name "$flavour")"
  palette "$flavour"
  mkdir -p "$(dirname "$KITTY_CURRENT_THEME")"
  cat > "$KITTY_CURRENT_THEME" <<EOF
