#!/usr/bin/env bash
set -Eeuo pipefail

ACTION="${1:-apply}"
FLAVOUR="${2:-mocha}"

CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE_DIR="$CONFIG_HOME/ricing"
SKETCHYBAR_DIR="$CONFIG_HOME/sketchybar"
SKETCHYBAR_ACTIVE_THEME="$SKETCHYBAR_DIR/helpers/active_theme.txt"
WALLPAPER_DIR="$CONFIG_HOME/wallpapers/catppuccin"
KITTY_CONFIG="$CONFIG_HOME/kitty/kitty.conf"
KITTY_CURRENT_THEME="$CONFIG_HOME/kitty/current-theme.conf"
STARSHIP_CONFIG="$CONFIG_HOME/starship.toml"
KITTY_OPACITY_SCRIPT="$CONFIG_HOME/scripts/kitty-opacity.sh"
JANKYBORDERS_SCRIPT="$CONFIG_HOME/scripts/jankyborders.sh"
SKETCHYVIM_SCRIPT="$CONFIG_HOME/scripts/sketchyvim-toggle.sh"
SOUND_SCRIPT="$CONFIG_HOME/scripts/aesthetic-sound.sh"
NVIM_STATE_DIR="${XDG_STATE_HOME:-$HOME/.local/state}/nvim"
DEFAULT_OPACITY="${CATPPUCCIN_TILING_OPACITY:-70}"

mkdir -p "$STATE_DIR" "$SKETCHYBAR_DIR" "$SKETCHYBAR_DIR/helpers"

mark_manual_theme_choice() {
  [[ "${CATPPUCCIN_AUTO_SYNC:-0}" == "1" ]] && return 0
  [[ "${CATPPUCCIN_KEEP_AUTO:-0}" == "1" ]] && return 0
  printf '0\n' > "$STATE_DIR/auto_appearance_enabled"
}

normalise_flavour() {
  local value
  value="$(printf '%s' "${1:-}" | tr '[:upper:]' '[:lower:]')"

  case "$value" in
    latte|frappe|macchiato|mocha) printf '%s\n' "$value" ;;
    catppuccin-latte) printf 'latte\n' ;;
    catppuccin-frappe) printf 'frappe\n' ;;
    catppuccin-macchiato) printf 'macchiato\n' ;;
    catppuccin-mocha) printf 'mocha\n' ;;
    *) printf 'mocha\n' ;;
  esac
}

title_flavour() {
  local value
  value="$(normalise_flavour "$1")"
  printf '%s%s\n' "$(printf '%s' "${value:0:1}" | tr '[:lower:]' '[:upper:]')" "${value:1}"
}

kitty_theme_name() {
  case "$(normalise_flavour "$1")" in
    latte) printf 'Catppuccin-Latte\n' ;;
    frappe) printf 'Catppuccin-Frappe\n' ;;
    macchiato) printf 'Catppuccin-Macchiato\n' ;;
    *) printf 'Catppuccin-Mocha\n' ;;
  esac
}

