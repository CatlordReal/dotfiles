# Generated by catppuccin-tiling-mode.sh
export CATPPUCCIN_FLAVOUR="$(normalise_flavour "$flavour")"
export BAR_COLOR=0xee$BASE
export ITEM_BG=0xcc$MANTLE
export ITEM_BG_ALT=0xaa$SURFACE0
